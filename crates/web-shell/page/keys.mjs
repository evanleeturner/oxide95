// The one map from a browser key to what `window::page::Page::hand` takes: the
// `KeyboardEvent.code` of a key to its Windows virtual key number. Keyed by the
// key's place, so a layout never changes what a program polls. `Tab` is left out on
// purpose: it always leaves the canvas, so a keyboard alone can never be trapped.
//
// Call: virtualKey("KeyA") gives 0x41; a key not in the map gives null.
